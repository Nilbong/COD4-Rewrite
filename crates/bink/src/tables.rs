/// Each tree's code lengths: for each code, one more than the most low bits
/// it shares with any other code (and at least its own bits).
pub fn tree_lengths(codes: &[u8; 16]) -> [u8; 16] {
    let mut out = [0u8; 16];
    for (i, &v) in codes.iter().enumerate() {
        let mut need = (8 - v.leading_zeros()).max(1);
        for (j, &w) in codes.iter().enumerate() {
            if i != j {
                need = need.max((v ^ w).trailing_zeros().min(8) + 1);
            }
        }
        out[i] = need as u8;
    }
    out
}

