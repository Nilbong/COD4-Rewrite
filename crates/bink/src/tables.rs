/// The 16 quantiser scales, as fractions.
const SCALES: [(u32, u32); 16] = [(1, 1), (4, 3), (5, 3), (2, 1), (8, 3), (7, 2), (4, 1), (5, 1), (6, 1), (8, 1), (12, 1), (17, 1), (22, 1), (28, 1), (34, 1), (44, 1)];

/// The dequantisers (16.16 fixed point), by quantiser and coefficient
/// index: base × the IDCT's AAN factors at that position × the scale.
pub fn quant(intra: bool) -> Vec<[i32; 64]> {
    let aan = |k: usize| if k == 0 { 1.0f64 } else { std::f64::consts::SQRT_2 * (k as f64 * std::f64::consts::PI / 16.0).cos() };
    let base = if intra { &INTRA_BASE } else { &INTER_BASE };
    SCALES
        .iter()
        .map(|&(n, d)| {
            std::array::from_fn(|i| {
                let p = SCAN[i] as usize;
                (base[i] as f64 / 16.0 * aan(p & 7) * aan(p >> 3) * 65536.0 * n as f64 / d as f64).round() as i32
            })
        })
        .collect()
}
