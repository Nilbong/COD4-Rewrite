/// A run block's scan path: visit order → position in the block.
pub fn path(k: usize) -> [u8; 64] {
    let mut out = [0u8; 64];
    for (r, row) in PATHS[k].iter().enumerate() {
        for (c, &order) in row.iter().enumerate() {
            out[order as usize] = (r * 8 + c) as u8;
        }
    }
    out
}

